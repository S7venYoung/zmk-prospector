#!/usr/bin/env python3
"""Original seven-segment bitmap glyphs; Pillow is needed only to regenerate."""
from pathlib import Path
from PIL import Image,ImageDraw
root=Path(__file__).resolve().parents[1]
# a,b,c,d,e,f,g; B is the instrument-style capital (8-shaped).
masks=dict(zip('0123456789',[0x3f,6,0x5b,0x4f,0x66,0x6d,0x7d,7,0x7f,0x6f]))
masks.update(dict(zip('ABCDEFGHIJKLMNOPQRSTUVWXYZ',[0x77,0x7f,0x39,0x5e,0x79,0x71,0x3d,0x76,0x06,0x1e,0x76,0x38,0x37,0x54,0x3f,0x73,0x67,0x50,0x6d,0x78,0x3e,0x3e,0x3e,0x76,0x6e,0x5b])))
masks.update({' ':0,'-':0x40,'.':0,'_':8})
def font(name,h,w,chars):
 packed=bytearray();ds=[(0,0,0,0,0,0)]
 for ch in chars:
  im=Image.new('L',(w*4,h*4));d=ImageDraw.Draw(im);t=max(2,round(h*.11));gap=1
  # Bevelled segments, inset one pixel to keep all ink within glyph bounds.
  def horiz(y):return [(t,y),(w-t,y),(w-1,y+t/2),(w-t,y+t),(t,y+t),(1,y+t/2)]
  def vert(x,y0,y1):return [(x+t/2,y0),(x+t,y0+t/2),(x+t,y1-t/2),(x+t/2,y1),(x,y1-t/2),(x,y0+t/2)]
  mid=(h-t)/2
  polys=[horiz(1),vert(w-t-1,t+gap,mid-gap),vert(w-t-1,mid+t+gap,h-t-gap),horiz(h-t-1),vert(1,mid+t+gap,h-t-gap),vert(1,t+gap,mid-gap),horiz(mid)]
  for bit,p in enumerate(polys):
   if masks[ch]&(1<<bit):d.polygon([(round(x*4),round(y*4)) for x,y in p],fill=255)
  if ch.isalpha() and name=='segment_18':
   # Compact square-stroke alphabet: R/N/W/M must remain recognisable.
   im=Image.new('L',(w*4,h*4));d=ImageDraw.Draw(im)
   paths={
    'C':[[(8,1),(2,1),(1,3),(1,13),(2,15),(8,15)]],
    'O':[[(2,1),(7,1),(8,3),(8,13),(7,15),(2,15),(1,13),(1,3),(2,1)]],
    'R':[[(1,15),(1,1),(7,1),(8,3),(8,6),(7,8),(1,8)],[(5,8),(8,15)]],
    'N':[[(1,15),(1,1),(8,15),(8,1)]],
    'E':[[(8,1),(1,1),(1,15),(8,15)],[(1,8),(7,8)]],
    'L':[[(1,1),(1,15),(8,15)]],
    'A':[[(1,15),(1,3),(3,1),(6,1),(8,3),(8,15)],[(1,8),(8,8)]],
    'Y':[[(1,1),(4.5,8),(8,1)],[(4.5,8),(4.5,15)]],
    'W':[[(1,1),(2,15),(4.5,10),(7,15),(8,1)]],
    'P':[[(1,15),(1,1),(7,1),(8,3),(8,6),(7,8),(1,8)]],
    'M':[[(1,15),(1,1),(4.5,7),(8,1),(8,15)]],
    'U':[[(1,1),(1,13),(3,15),(6,15),(8,13),(8,1)]],
    'S':[[(8,1),(2,1),(1,3),(1,6),(3,8),(6,8),(8,10),(8,13),(7,15),(1,15)]],
    'B':[[(1,1),(1,15),(6,15),(8,13),(8,10),(6,8),(1,8)],[(1,1),(6,1),(8,3),(8,6),(6,8)]],
    'F':[[(1,15),(1,1),(8,1)],[(1,8),(7,8)]]}
   for path in paths.get(ch,[]):
    d.line([(round(x*w/9*4),round(y*h/16*4)) for x,y in path],fill=255,width=6,joint='curve')
   if ch not in paths: # Preserve generated segments for less common letters.
    for bit,poly in enumerate(polys):
     if masks[ch]&(1<<bit):d.polygon([(round(x*4),round(y*4)) for x,y in poly],fill=255)
  levels=[round(v/85) for v in im.resize((w,h),Image.Resampling.LANCZOS).tobytes()];start=len(packed)
  while len(levels)%4:levels.append(0)
  packed.extend((levels[i]<<6)|(levels[i+1]<<4)|(levels[i+2]<<2)|levels[i+3] for i in range(0,len(levels),4));ds.append((start,(w+3)*16,w,h,0,1))
 lines=['/* SPDX-License-Identifier: MIT; original geometric glyphs, generated by make-segment-fonts.py. */','#include <lvgl.h>','static const uint8_t bitmap[]={']
 for i in range(0,len(packed),16):lines.append(','.join('0x%02x'%v for v in packed[i:i+16])+',')
 lines+=['};','static const lv_font_fmt_txt_glyph_dsc_t glyphs[]={']
 lines += ['{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d},'%v for v in ds]
 first=ord(chars[0]);lines+=['};','static const uint16_t unicode[]={'+','.join(str(ord(c)-first) for c in chars)+'};',f'static const lv_font_fmt_txt_cmap_t cmaps[]={{{{.range_start={first},.range_length={ord(chars[-1])-first+1},.glyph_id_start=1,.unicode_list=unicode,.list_length={len(chars)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}}};','static const lv_font_fmt_txt_dsc_t dsc={.glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=cmaps,.cmap_num=1,.bpp=2};',f'const lv_font_t {name}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={h+2},.base_line=1,.dsc=&dsc}};']
 (root/'src'/f'{name}.c').write_text('\n'.join(lines)+'\n');print(name,len(packed))
alpha=' -.'+'0123456789'+'ABCDEFGHIJKLMNOPQRSTUVWXYZ_'
for name,h,w,chars in [('segment_18',16,9,alpha),('segment_26',24,13,' -0123456789'),('segment_36',34,20,' ABES'),('segment_80',78,36,'0123456789'),('segment_48',46,22,'0123456789')]:font(name,h,w,chars)
