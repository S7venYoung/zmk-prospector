#!/usr/bin/env python3
"""Encode the original-style cassette artwork and native theme fonts.
Raster artwork is RGB565 in flash (no full-image ARGB decode allocation).
"""
from pathlib import Path
import runpy
from PIL import Image
root=Path(__file__).resolve().parents[1]
generate=runpy.run_path(str(root/'scripts/make-industrial-fonts.py'))['generate']
generate('blueprint_title_40',list(range(32,96)),1.10,.70,43,6,bpp=2,treatment='blueprint')
generate('terminal_title_52',list(range(32,96)),1.20,.95,56,9,bpp=2,treatment='terminal')
generate('blueprint_numeric_32',[32,45]+list(range(48,58)),.38,32/56,34,5,bpp=2)
# Remove the source image's empty surround before encoding the native-size panel.
# Keep only the mechanical tape window; the native renderer supplies the player chassis.
image=Image.open(root/'artwork/tape-source.png').convert('RGB')
image=image.crop((142,120,1518,696)).resize((256,108),Image.Resampling.LANCZOS)
pixels=[(r>>3)<<11|(g>>2)<<5|(b>>3) for r,g,b in image.getdata()]
lines=['/* SPDX-License-Identifier: MIT; generated by scripts/make-concept-assets.py */','#include <lvgl.h>','static const uint16_t pixels[] = {']
for i in range(0,len(pixels),16):lines.append('    '+','.join(f'0x{v:04x}' for v in pixels[i:i+16])+',')
lines+=['};','const lv_image_dsc_t tape_cassette_image = {','.header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565,.w=256,.h=108,.stride=512},','.data_size=sizeof(pixels),.data=(const uint8_t *)pixels','};']
(root/'src/tape_cassette_image.c').write_text('\n'.join(lines)+'\n')
print('cassette artwork:',len(pixels)*2,'bytes in flash')
