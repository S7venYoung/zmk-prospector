#!/usr/bin/env python3
"""Generate compact native LVGL fonts from the repository's Impact 56 bitmap.
Requires Pillow; generated C assets are the only firmware dependencies.
"""
from pathlib import Path
import re
from PIL import Image

root = Path(__file__).resolve().parents[1]
source = (root / 'fonts/source/impact_56.c').read_text()
bitmap_part = source.split('glyph_bitmap[] = {', 1)[1].split('};', 1)[0]
bitmap_part = re.sub(r'/\*.*?\*/', '', bitmap_part, flags=re.S)
bitmap = bytes(int(v, 16) for v in re.findall(r'0x([0-9a-fA-F]+)', bitmap_part))
glyphs = [tuple(map(int, row)) for row in re.findall(
    r'\{\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), '
    r'\.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)\}', source)]

def generate(name, codepoints, sx, sy, line_height, baseline):
    packed = bytearray(); descriptors = [(0, 0, 0, 0, 0, 0)]
    for cp in codepoints:
        offset, advance, width, height, ox, oy = glyphs[cp - 32 + 1]
        new_w, new_h = round(width * sx), round(height * sy)
        start = len(packed)
        if width and height:
            pixels = [((bitmap[offset + p // 2] >> (0 if p % 2 else 4)) & 15) * 17
                      for p in range(width * height)]
            image = Image.new('L', (width, height)); image.putdata(pixels)
            image = image.resize((new_w, new_h), Image.Resampling.LANCZOS)
            levels = [min(15, max(0, round(p / 17))) for p in image.tobytes()]
            if len(levels) % 2: levels.append(0)
            packed.extend((levels[i] << 4) | levels[i + 1] for i in range(0, len(levels), 2))
        descriptors.append((start, round(advance * sx), new_w, new_h, round(ox * sx), round(oy * sy)))
    first = min(codepoints)
    lines = ['/* SPDX-License-Identifier: MIT',
             ' * Derived from fonts/source/impact_56.c.',
             ' * Generated by scripts/make-industrial-fonts.py; 4 bpp. */',
             '#include <lvgl.h>', '', 'static const uint8_t glyph_bitmap[] = {']
    for i in range(0, len(packed), 16):
        lines.append('    ' + ', '.join(f'0x{x:02x}' for x in packed[i:i + 16]) + ',')
    lines += ['};', 'static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {']
    for idx, adv, w, h, ox, oy in descriptors:
        lines.append(f'    {{.bitmap_index={idx}, .adv_w={adv}, .box_w={w}, .box_h={h}, .ofs_x={ox}, .ofs_y={oy}}},')
    lines += ['};',
              'static const uint16_t unicode_list[] = {' + ', '.join(str(c - first) for c in codepoints) + '};',
              'static const lv_font_fmt_txt_cmap_t cmaps[] = {{',
              f'    .range_start={first}, .range_length={max(codepoints)-first+1}, .glyph_id_start=1,',
              '    .unicode_list=unicode_list, .glyph_id_ofs_list=NULL,',
              f'    .list_length={len(codepoints)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY',
              '}};', 'static const lv_font_fmt_txt_dsc_t font_dsc = {',
              '    .glyph_bitmap=glyph_bitmap, .glyph_dsc=glyph_dsc, .cmaps=cmaps,',
              '    .kern_dsc=NULL, .kern_scale=0, .cmap_num=1, .bpp=4,',
              '    .kern_classes=0, .bitmap_format=0', '};',
              f'const lv_font_t {name} = {{',
              '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,',
              '    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
              f'    .line_height={line_height}, .base_line={baseline}, .dsc=&font_dsc', '};', '']
    target = root / f'src/{name}.c'
    target.write_text('\n'.join(lines))
    print(f'{name}: {len(packed)} bitmap bytes, {len(codepoints)} glyphs')

generate('industrial_numeric_32', [32, 37, 45, 46] + list(range(48, 58)), 32/56, 32/56, 34, 5)
generate('industrial_display_56', list(range(32, 96)), 1.70, 1, 58, 9)
generate('industrial_brand_28', sorted(set(map(ord, ' .CORNE'))), .5, .5, 29, 5)

generate('industrial_battery_32', [32, 45] + list(range(48, 58)), 0.70*32/56, 32/56, 34, 5)
